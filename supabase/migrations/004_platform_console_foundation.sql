-- PARYX PLATFORM
-- Migration 004: Paryx Console foundation
--
-- PURPOSE
-- 1. Create a platform-level permission layer that is separate from club roles.
-- 2. Provide secure RPCs for the internal Paryx Console.
-- 3. Allow platform owners/admins to create, inspect, suspend and reactivate
--    tenant clubs without exposing elevated database credentials to browsers.
-- 4. Create a platform audit trail.
--
-- IMPORTANT
-- After this migration succeeds, run the separate bootstrap file:
-- supabase/setup/004_bootstrap_platform_owner.sql
-- to make your existing Supabase Auth account the first platform_owner.

begin;

-- =========================================================
-- PLATFORM USERS
-- =========================================================

create table if not exists public.platform_users (
    user_id uuid primary key
        references auth.users(id)
        on delete cascade,

    role text not null,
    is_active boolean not null default true,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint platform_users_role_valid
        check (
            role in (
                'platform_owner',
                'platform_admin',
                'platform_support'
            )
        )
);

alter table public.platform_users
    enable row level security;

-- Deliberately no direct browser policies.
-- All Console reads/writes go through SECURITY DEFINER RPCs after a role check.


-- =========================================================
-- PLATFORM AUDIT LOG
-- =========================================================

create table if not exists public.platform_audit_log (
    id bigint generated by default as identity primary key,

    actor_user_id uuid
        references auth.users(id)
        on delete set null,

    actor_role text,

    action text not null,

    club_id uuid
        references public.clubs(id)
        on delete set null,

    target_user_id uuid
        references auth.users(id)
        on delete set null,

    details jsonb not null default '{}'::jsonb,

    created_at timestamptz not null default now(),

    constraint platform_audit_action_not_blank
        check (length(trim(action)) > 0)
);

create index if not exists platform_audit_log_created_at_idx
    on public.platform_audit_log(created_at desc);

create index if not exists platform_audit_log_club_id_idx
    on public.platform_audit_log(club_id);

create index if not exists platform_audit_log_actor_user_id_idx
    on public.platform_audit_log(actor_user_id);

alter table public.platform_audit_log
    enable row level security;

-- Deliberately no direct browser policies.


-- =========================================================
-- PLATFORM ACCESS HELPER
-- =========================================================

create or replace function public.is_platform_user(
    p_roles text[] default null
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.platform_users as pu
        where pu.user_id = auth.uid()
          and pu.is_active = true
          and (
              p_roles is null
              or pu.role = any(p_roles)
          )
    );
$$;

revoke all
on function public.is_platform_user(text[])
from public, anon;

grant execute
on function public.is_platform_user(text[])
to authenticated;


