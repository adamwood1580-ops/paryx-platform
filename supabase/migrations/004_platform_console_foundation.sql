create or replace function public.platform_get_audit(
    p_limit integer default 100
)
returns table (
    audit_id bigint,
    actor_email text,
    actor_role text,
    action text,
    club_id uuid,
    club_name text,
    target_email text,
    details jsonb,
    created_at timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_limit integer;
begin
    if auth.uid() is null
       or not public.is_platform_user(null) then
        raise exception 'Paryx Console access required.';
    end if;

    v_limit := greatest(
        1,
        least(coalesce(p_limit, 100), 250)
    );

    return query
    select
        pal.id,
        actor.email::text,
        pal.actor_role,
        pal.action,
        pal.club_id,
        c.name,
        target.email::text,
        pal.details,
        pal.created_at
    from public.platform_audit_log as pal
    left join auth.users as actor
        on actor.id = pal.actor_user_id
    left join auth.users as target
        on target.id = pal.target_user_id
    left join public.clubs as c
        on c.id = pal.club_id
    order by pal.created_at desc
    limit v_limit;
end;
$$;

